from enum import Enum


class AuctionType(str, Enum):
    STANDARD = "STANDARD"
    BRITISH = "BRITISH"


class AuctionStatus(str, Enum):
    SCHEDULED = "SCHEDULED"
    ACTIVE = "ACTIVE"
    CLOSED = "CLOSED"
    FORCE_CLOSED = "FORCE_CLOSED"


class ExtensionTrigger(str, Enum):
    BID_IN_LAST_X = "BID_IN_LAST_X"
    ANY_RANK_CHANGE_IN_LAST_X = "ANY_RANK_CHANGE_IN_LAST_X"
    L1_CHANGE_IN_LAST_X = "L1_CHANGE_IN_LAST_X"


class AuctionEventType(str, Enum):
    AUCTION_CREATED = "AUCTION_CREATED"
    AUCTION_STARTED = "AUCTION_STARTED"
    BID_PLACED = "BID_PLACED"
    TIME_EXTENDED = "TIME_EXTENDED"
    EXTENSION_SKIPPED_AT_FORCED_CLOSE = "EXTENSION_SKIPPED_AT_FORCED_CLOSE"
    AUCTION_CLOSED = "AUCTION_CLOSED"
    AUCTION_FORCE_CLOSED = "AUCTION_FORCE_CLOSED"
